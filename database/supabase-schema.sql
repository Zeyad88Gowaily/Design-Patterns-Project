create table if not exists public.donors (
    id integer generated by default as identity primary key,
    data jsonb not null
);

create table if not exists public.donations (
    id integer generated by default as identity primary key,
    donor_id integer not null references public.donors(id) on delete restrict,
    data jsonb not null
);

create table if not exists public.volunteers (
    id integer generated by default as identity primary key,
    data jsonb not null
);

create table if not exists public.events (
    id integer generated by default as identity primary key,
    data jsonb not null
);

create table if not exists public.event_volunteers (
    id integer generated by default as identity primary key,
    event_id integer not null references public.events(id) on delete cascade,
    volunteer_id integer not null references public.volunteers(id) on delete cascade
);

create table if not exists public.beneficiaries (
    id integer generated by default as identity primary key,
    data jsonb not null
);

create table if not exists public.lookups (
    id integer generated by default as identity primary key,
    data jsonb not null
);

create table if not exists public.registrations (
    id integer generated by default as identity primary key,
    event_id integer not null references public.events(id) on delete cascade,
    volunteer_id integer not null references public.volunteers(id) on delete cascade,
    data jsonb not null,
    constraint registrations_event_volunteer_unique unique (event_id, volunteer_id)
);

create table if not exists public.tickets (
    id integer generated by default as identity primary key,
    event_id integer not null references public.events(id) on delete cascade,
    volunteer_id integer not null references public.volunteers(id) on delete cascade,
    data jsonb not null,
    constraint tickets_event_volunteer_unique unique (event_id, volunteer_id)
);

do $$
declare
    table_name text;
    app_tables text[] := array[
        'donors',
        'donations',
        'volunteers',
        'events',
        'event_volunteers',
        'beneficiaries',
        'lookups',
        'registrations',
        'tickets'
    ];
begin
    foreach table_name in array app_tables loop
        execute format('alter table public.%I enable row level security', table_name);
        execute format(
            'drop policy if exists authenticated_full_access on public.%I',
            table_name
        );
        execute format(
            'create policy authenticated_full_access on public.%I for all to authenticated using (true) with check (true)',
            table_name
        );
    end loop;
end
$$;

grant select, insert, update, delete on
    public.donors,
    public.donations,
    public.volunteers,
    public.events,
    public.event_volunteers,
    public.beneficiaries,
    public.lookups,
    public.registrations,
    public.tickets
to authenticated;

grant usage, select on all sequences in schema public to authenticated;

insert into public.lookups (data)
select jsonb_build_object('name', seed.name, 'category', seed.category)
from (values
    ('First Aid', 'SKILL'),
    ('Teaching', 'SKILL'),
    ('Cooking', 'SKILL'),
    ('Driving', 'SKILL'),
    ('IT Support', 'SKILL'),
    ('Fundraiser', 'EVENT_TYPE'),
    ('Workshop', 'EVENT_TYPE'),
    ('Community Clean', 'EVENT_TYPE'),
    ('Online', 'DONATION_TYPE'),
    ('Check', 'DONATION_TYPE'),
    ('In-Kind', 'DONATION_TYPE'),
    ('Food', 'NEED_TYPE'),
    ('Shelter', 'NEED_TYPE'),
    ('Education', 'NEED_TYPE'),
    ('Healthcare', 'NEED_TYPE')
) as seed(name, category)
where not exists (
    select 1
    from public.lookups existing
    where existing.data->>'name' = seed.name
      and existing.data->>'category' = seed.category
);
